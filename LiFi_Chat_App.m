    function sendMessage(~,~)

        msg = strtrim(string(messageBox.Value));

        if strlength(msg) == 0

            statusMetric.Text = 'ENTER A MESSAGE';
            statusMetric.FontColor = ERROR;

            return;

        end

        if any(double(char(msg)) > 127)

            statusMetric.Text = 'ASCII TEXT ONLY';
            statusMetric.FontColor = ERROR;

            return;

        end

        if isvalid(emptyText)
            delete(emptyText);
        end

        %% ========================================================
        % TEXT -> ASCII -> BINARY
        % ========================================================

        asciiData = uint8(char(msg));

        bitMatrix = dec2bin(asciiData,8).' - '0';

        txBits = reshape(bitMatrix,1,[]);

        txBitsGlobal = txBits;

        transmissionStage.Text = ...
            '1. TEXT -> ASCII -> BINARY';

        transmissionStage.FontColor = LAVENDER;

        transmissionProgress.Text = ...
            sprintf('Encoding %d character(s)',strlength(msg));

        %% CHARACTER TABLE

        asciiRows = cell(length(asciiData),5);

        for ii = 1:length(asciiData)

            ch = char(asciiData(ii));

            binaryValue = dec2bin(asciiData(ii),8);

            asciiRows{ii,1} = ii;
            asciiRows{ii,2} = ch;
            asciiRows{ii,3} = double(asciiData(ii));
            asciiRows{ii,4} = binaryValue;

            ookText = binaryValue;

            ookText = strrep(ookText,'1','ON ');
            ookText = strrep(ookText,'0','OFF ');

            asciiRows{ii,5} = ookText;

        end

        conversionTable.Data = asciiRows;

        %% ASCII LIVE

        asciiLive.Value = { ...
            ['Original Text : ' char(msg)]; ...
            ''; ...
            'CHARACTER -> ASCII -> 8-BIT BINARY'; ...
            ''; ...
            sprintf('Characters : %d',length(asciiData)); ...
            ''; ...
            'Conversion:'};

        for ii = 1:length(asciiData)

            currentChar = char(asciiData(ii));
            currentASCII = double(asciiData(ii));
            currentBinary = dec2bin(asciiData(ii),8);

            asciiLive.Value{end+1} = sprintf( ...
                '%s -> %d -> %s', ...
                currentChar, ...
                currentASCII, ...
                currentBinary);

        end

        %% BIT STREAM

        bitStreamLive.Value = { ...
            'TX BINARY STREAM'; ...
            ''; ...
            num2str(txBits); ...
            ''; ...
            'OOK RULE:'; ...
            '1 = LED ON'; ...
            '0 = LED OFF'};

        drawnow;

        %% ========================================================
        % TRANSMISSION STATE
        % ========================================================

        statusHeader.Text = 'Transmitting...';
        statusHeader.FontColor = LED_RED;
        statusDot.FontColor = LED_RED;

        txStatus.Text = '● TRANSMITTING';
        txStatus.FontColor = LED_RED;

        rxStatus.Text = '● WAITING';
        rxStatus.FontColor = WARNING;

        statusMetric.Text = sprintf( ...
            'TRANSMITTING  •  %s  •  %.1f dB SNR', ...
            DataRateText,SNR_dB);

        statusMetric.FontColor = LED_RED;

        linkLabel.Text = 'TRANSMITTING...';
        linkLabel.FontColor = LED_RED;

        %% LED BLINK

        for blink = 1:6

            blinkState = ~blinkState;

            if blinkState

                ledIndicator.FontColor = LED_RED;
                photodiodeIndicator.FontColor = LED_IDLE;

            else

                ledIndicator.FontColor = LED_IDLE;
                photodiodeIndicator.FontColor = LED_RED;

            end

            drawnow;
            pause(0.12);

        end

        %% ========================================================
        % OOK MODULATION
        % ========================================================

        txSignal = repelem( ...
            double(txBits), ...
            SamplesPerBit);

        transmissionStage.Text = ...
            '2. BINARY -> OOK MODULATION';

        transmissionStage.FontColor = LAVENDER;

        transmissionProgress.Text = sprintf( ...
            'Sending %d optical samples at %s', ...
            length(txSignal),DataRateText);

        transmissionFlow.Value = { ...
            ['TEXT : ' char(msg)]; ...
            ''; ...
            'STEP 1 -> ASCII values'; ...
            'STEP 2 -> 8-bit binary'; ...
            'STEP 3 -> OOK modulation'; ...
            '          1 = LED ON'; ...
            '          0 = LED OFF'; ...
            sprintf('STEP 4 -> Optical channel at %.1f m',ChannelDistance); ...
            sprintf('          SNR = %.1f dB',SNR_dB); ...
            'STEP 5 -> Photodiode detection'; ...
            'STEP 6 -> Binary -> ASCII -> Text'; ...
            ''; ...
            'Transmission is in progress...'};

        drawnow;

        %% ========================================================
        % OPTICAL CHANNEL
        % ========================================================

        rng('shuffle');

        channelGain = ...
            (0.5/ChannelDistance)^2;

        attenuatedSignal = ...
            txSignal * channelGain;

        signalPower = ...
            max(mean(attenuatedSignal.^2),1e-6);

        noisePower = ...
            signalPower/(10^(SNR_dB/10));

        noise = ...
            sqrt(noisePower) * randn(size(attenuatedSignal));

        rxSignal = ...
            attenuatedSignal + noise;

        transmissionStage.Text = ...
            '3. OOK -> OPTICAL CHANNEL';

        transmissionStage.FontColor = LED_RED;

        transmissionProgress.Text = sprintf( ...
            'LED -> Channel -> Photodiode | Gain %.6f | SNR %.1f dB', ...
            channelGain,SNR_dB);

        drawnow;

        %% ========================================================
        % PHOTODIODE / DEMODULATION
        % ========================================================

        sampleIndex = ...
            round(SamplesPerBit/2): ...
            SamplesPerBit:length(rxSignal);

        rxSamples = ...
            rxSignal(sampleIndex);

        threshold = ...
            channelGain/2;

        rxBits = ...
            double(rxSamples >= threshold);

        %% OPTIONAL FORCED ERROR

        if FORCE_ERROR_DEMO

            errorMask = ...
                rand(size(rxBits)) < ...
                ForcedBitErrorProbability;

            rxBits(errorMask) = ...
                1 - rxBits(errorMask);

        end

        rxBitsGlobal = rxBits;

        transmissionStage.Text = ...
            '4. PHOTODIODE -> BINARY';

        transmissionStage.FontColor = LAVENDER;

        transmissionProgress.Text = sprintf( ...
            'Threshold = %.6f | Received %d bits', ...
            threshold,length(rxBits));

        drawnow;

        %% ========================================================
        % BER
        % ========================================================

        bitErrorsGlobal = ...
            sum(txBits ~= rxBits);

        berGlobal = ...
            bitErrorsGlobal / max(length(txBits),1);

        %% ========================================================
        % BINARY -> ASCII -> TEXT
        % ========================================================

        rxMatrix = ...
            reshape(rxBits,8,[]).';

        rxASCII = ...
            uint8(bin2dec(char(rxMatrix + '0')));

        receivedMessage = ...
            string(char(rxASCII.'));

        %% RX TABLE

        rxRows = cell(length(rxASCII),5);

        for ii = 1:length(rxASCII)

            currentChar = char(rxASCII(ii));
            currentASCII = double(rxASCII(ii));
            currentBinary = dec2bin(rxASCII(ii),8);

            startBit = (ii-1)*8 + 1;
            endBit = ii*8;

            txCharBits = txBits(startBit:endBit);
            rxCharBits = rxBits(startBit:endBit);

            charErrors = ...
                sum(txCharBits ~= rxCharBits);

            rxRows{ii,1} = ii;
            rxRows{ii,2} = currentChar;
            rxRows{ii,3} = currentASCII;
            rxRows{ii,4} = currentBinary;

            rxRows{ii,5} = ...
                sprintf('%d error(s)',charErrors);

        end

        conversionTable.ColumnName = ...
            {'No.','RX Character','RX ASCII','RX Binary','Result'};

        conversionTable.Data = rxRows;

        %% ========================================================
        % FINAL TRANSMISSION FLOW
        % ========================================================

        if bitErrorsGlobal == 0

            transmissionStage.Text = ...
                'TRANSMISSION SUCCESSFUL';

            transmissionStage.FontColor = SUCCESS;

        else

            transmissionStage.Text = ...
                'TRANSMISSION WITH ERRORS';

            transmissionStage.FontColor = ERROR;

        end

        transmissionProgress.Text = sprintf( ...
            'TX -> RX complete | %d errors | BER %.6f', ...
            bitErrorsGlobal,berGlobal);

        transmissionFlow.Value = { ...
            ['TEXT : ' char(msg)]; ...
            ''; ...
            'TRANSMITTER'; ...
            'Text -> ASCII -> Binary -> OOK'; ...
            ''; ...
            sprintf('Channel Distance : %.1f m',ChannelDistance); ...
            sprintf('SNR              : %.1f dB',SNR_dB); ...
            sprintf('Data Rate         : %s',DataRateText); ...
            ''; ...
            'RECEIVER'; ...
            'Photodiode -> Threshold -> Binary'; ...
            'Binary -> ASCII -> Text'; ...
            ''; ...
            ['Received Text : ' char(receivedMessage)]; ...
            sprintf('Bit Errors    : %d',bitErrorsGlobal); ...
            sprintf('BER           : %.6f',berGlobal)};

        asciiLive.Value{end+1} = '';
        asciiLive.Value{end+1} = ...
            ['RECEIVED TEXT : ' char(receivedMessage)];

        bitStreamLive.Value{end+1} = '';
        bitStreamLive.Value{end+1} = 'RX BINARY STREAM';
        bitStreamLive.Value{end+1} = num2str(rxBits);

        drawnow;

        %% ========================================================
        % CHAT HISTORY
        % ========================================================

        tnow = datestr(now,'HH:MM');

        messageHistory{end+1} = char(msg);
        timeHistory{end+1} = tnow;

        transmittedHistory{end+1} = char(msg);
        receivedHistory{end+1} = char(receivedMessage);

        renderChatHistory();

        %% ========================================================
        % RECEIVER STATE
        % ========================================================

        statusHeader.Text = 'Receiving...';
        statusHeader.FontColor = DEEP;

        txStatus.Text = '● SENT';
        txStatus.FontColor = SUCCESS;

        rxStatus.Text = '● RECEIVING';
        rxStatus.FontColor = LAVENDER;

        statusMetric.Text = ...
            'RECEIVING  •  PHOTODIODE';

        statusMetric.FontColor = LAVENDER;

        linkLabel.Text = ...
            'OPTICAL SIGNAL DETECTED';

        linkLabel.FontColor = LAVENDER;

        %% PHOTODIODE ACTIVITY

        for k = 1:4

            photodiodeIndicator.FontColor = LED_RED;

            drawnow;
            pause(0.10);

            photodiodeIndicator.FontColor = LED_IDLE;

            drawnow;
            pause(0.08);

        end

        %% ========================================================
        % FINAL STATUS
        % ========================================================

        statusHeader.Text = ...
            'LiFi Connected';

        statusHeader.FontColor = SUCCESS;
        statusDot.FontColor = SUCCESS;

        ledIndicator.FontColor = LED_GREEN;
        photodiodeIndicator.FontColor = LED_GREEN;

        txStatus.Text = '● READY';
        txStatus.FontColor = SUCCESS;

        if bitErrorsGlobal == 0

            rxStatus.Text = '● MESSAGE RECEIVED';
            rxStatus.FontColor = SUCCESS;

            statusMetric.Text = ...
                'SUCCESS  |  MESSAGE RECEIVED';

            statusMetric.FontColor = SUCCESS;

            linkLabel.Text = ...
                'LINK ACTIVE  •  DATA RECEIVED';

            linkLabel.FontColor = SUCCESS;

        else

            rxStatus.Text = '● ERRORS DETECTED';
            rxStatus.FontColor = ERROR;

            statusMetric.Text = sprintf( ...
                'RECEIVED WITH %d BIT ERROR(S)', ...
                bitErrorsGlobal);

            statusMetric.FontColor = ERROR;

            linkLabel.Text = ...
                'LINK ACTIVE  •  BIT ERRORS PRESENT';

            linkLabel.FontColor = ERROR;

        end

        %% ========================================================
        % UPDATE METRICS
        % ========================================================

        messageMetric.Text = char(msg);

        bitsMetric.Text = ...
            sprintf('%d',length(txBits));

        berMetric.Text = ...
            sprintf('%.4f',berGlobal);

        berCard.UserData.Text = ...
            sprintf('%.4f',berGlobal);

        errorCard.UserData.Text = ...
            sprintf('%d',bitErrorsGlobal);

        snrCard.UserData.Text = ...
            sprintf('%.1f dB',SNR_dB);

        throughputCard.UserData.Text = ...
            DataRateText;

        %% PERFORMANCE

        perfText.Value = { ...
            ['Message             ' char(msg)]; ...
            ''; ...
            sprintf('Characters          %d',strlength(msg)); ...
            sprintf('Total Bits          %d',length(txBits)); ...
            sprintf('Bit Errors          %d',bitErrorsGlobal); ...
            sprintf('BER                 %.4f',berGlobal); ...
            ''; ...
            'Modulation          OOK'; ...
            ['Data Rate           ' DataRateText]; ...
            sprintf('SNR                 %.1f dB',SNR_dB); ...
            sprintf('Distance            %.1f m',ChannelDistance); ...
            ''; ...
            'Transmission        COMPLETED'};

        %% ACTUAL GRAPHS

        updateGraphs( ...
            msg, ...
            txSignal, ...
            rxSignal, ...
            txBits, ...
            rxBits);

        messageBox.Value = '';

    end

