% ================================================================

    function updateGraphs( ...
            msg, ...
            txSignalInput, ...
            rxSignalInput, ...
            txBitsInput, ...
            rxBitsInput)

        %% TEXT -> BITS

        asciiData = uint8(char(msg));

        bitMatrix = dec2bin(asciiData,8).' - '0';

        bits = reshape(bitMatrix,1,[]);

        %% CREATE SIGNAL IF NOT PROVIDED

        if nargin < 2 || isempty(txSignalInput)

            txSignal = ...
                repelem(double(bits),SamplesPerBit);

            rng(10);

            gainForGraph = ...
                (0.5/ChannelDistance)^2;

            attenuated = ...
                txSignal * gainForGraph;

            signalPower = ...
                max(mean(attenuated.^2),1e-6);

            noisePower = ...
                signalPower/(10^(SNR_dB/10));

            noise = ...
                sqrt(noisePower)*randn(size(attenuated));

            rxSignal = ...
                attenuated + noise;

            sampleIndex = ...
                round(SamplesPerBit/2): ...
                SamplesPerBit:length(rxSignal);

            rxSamples = ...
                rxSignal(sampleIndex);

            threshold = gainForGraph/2;

            rxBits = ...
                double(rxSamples >= threshold);

        else

            txSignal = txSignalInput;
            rxSignal = rxSignalInput;
            rxBits = rxBitsInput;

        end

        sample = 1:length(txSignal);

        %% TX GRAPH

        cla(axTX);

        plot(axTX, ...
            sample, ...
            txSignal, ...
            'LineWidth',1.7, ...
            'Color',LAVENDER);

        ylim(axTX,[-0.2 1.2]);

        title(axTX, ...
            'Transmitted OOK Signal', ...
            'FontSize',13);

        xlabel(axTX,'Sample');
        ylabel(axTX,'LED Intensity');

        grid(axTX,'on');

        %% RX GRAPH

        cla(axRX);

        plot(axRX, ...
            sample, ...
            rxSignal, ...
            'LineWidth',0.9, ...
            'Color',DEEP);

        hold(axRX,'on');

        gainForGraph = ...
            (0.5/ChannelDistance)^2;

        threshold = ...
            gainForGraph/2;

        yline(axRX, ...
            threshold, ...
            '--', ...
            'Threshold', ...
            'LineWidth',1.1, ...
            'Color',LAVENDER);

        hold(axRX,'off');

        title(axRX, ...
            sprintf('Received Signal - SNR = %.1f dB',SNR_dB), ...
            'FontSize',13);

        xlabel(axRX,'Sample');
        ylabel(axRX,'Photodiode Output');

        grid(axRX,'on');

        %% TX VS RX

        cla(axBits);

        bitNumber = 1:length(bits);

        plot(axBits, ...
            bitNumber, ...
            bits, ...
            'o-', ...
            'LineWidth',1.3, ...
            'MarkerSize',5, ...
            'Color',LAVENDER);

        hold(axBits,'on');

        plot(axBits, ...
            bitNumber, ...
            rxBits, ...
            'o--', ...
            'LineWidth',1.3, ...
            'MarkerSize',4, ...
            'Color',DEEP);

        errorPositions = find(bits ~= rxBits);

        if ~isempty(errorPositions)

            plot(axBits, ...
                errorPositions, ...
                rxBits(errorPositions), ...
                'x', ...
                'MarkerSize',10, ...
                'LineWidth',2, ...
                'Color',ERROR);

        end

        hold(axBits,'off');

        title(axBits, ...
            sprintf('Transmitted vs Received Bits - Errors = %d', ...
            sum(bits ~= rxBits)), ...
            'FontSize',13);

        xlabel(axBits,'Bit Number');
        ylabel(axBits,'Bit Value');

        ylim(axBits,[-0.2 1.2]);

        legend(axBits, ...
            {'Transmitted Bits','Received Bits','Bit Errors'}, ...
            'Location','best');

        grid(axBits,'on');

        %% ========================================================
        % BER VS DISTANCE
        % ========================================================

        berDistance = zeros(size(Distance));

        rng(25);

        testBits = randi([0 1],5000,1);

        for k = 1:length(Distance)

            d = Distance(k);

            gain = (0.5/d)^2;

            received = double(testBits)*gain;

            signalPowerD = ...
                max(mean(received.^2),1e-9);

            noisePowerD = ...
                signalPowerD/(10^(SNR_dB/10));

            noiseD = ...
                sqrt(noisePowerD)*randn(size(received));

            received = ...
                received + noiseD;

            thresholdD = gain/2;

            recovered = ...
                received >= thresholdD;

            berDistance(k) = ...
                mean(recovered ~= testBits);

        end

        berDistance = ...
            max(berDistance,1e-5);

        cla(axBER);

        semilogy(axBER, ...
            Distance, ...
            berDistance, ...
            'o-', ...
            'LineWidth',1.7, ...
            'MarkerSize',6, ...
            'Color',LAVENDER);

        title(axBER, ...
            sprintf('BER vs Distance - SNR = %.1f dB',SNR_dB), ...
            'FontSize',14);

        xlabel(axBER,'Distance (m)');
        ylabel(axBER,'Bit Error Rate (BER)');

        ylim(axBER,[1e-5 1]);

        grid(axBER,'on');

        %% ========================================================
        % CHANNEL GAIN
        % ========================================================

        channelGain = ...
            (0.5./Distance).^2;

        %% RECEIVED POWER
        % ========================================================

        P_LED = 1;

        receivedPower = ...
            P_LED * channelGain * 1e-4;

        cla(axPower);

        plot(axPower, ...
            Distance, ...
            receivedPower, ...
            'o-', ...
            'LineWidth',1.7, ...
